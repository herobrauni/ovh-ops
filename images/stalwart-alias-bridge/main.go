package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"net/http"
	"os"
	"os/signal"
	"strings"
	"syscall"
	"time"
)

const (
	defaultListenAddr  = ":8080"
	defaultStalwartURL = "http://stalwart-mgmt.stalwart.svc.cluster.local:8080"
	requestTimeout     = 10 * time.Second
)

type bridge struct {
	stalwartURL string
	client      *http.Client
	logger      *slog.Logger
}

type addyCreateRequest struct {
	Domain      string `json:"domain"`
	Description string `json:"description"`
}

type addyCreateResponse struct {
	Data struct {
		Email string `json:"email"`
	} `json:"data"`
}

type jmapSession struct {
	PrimaryAccounts map[string]string `json:"primaryAccounts"`
}

type jmapRequest struct {
	Using       []string `json:"using"`
	MethodCalls [][]any  `json:"methodCalls"`
}

type jmapResponse struct {
	MethodResponses [][]json.RawMessage `json:"methodResponses"`
}

type maskedEmailSetPayload struct {
	Created    map[string]struct{ Email string `json:"email"` }      `json:"created"`
	NotCreated map[string]struct{ Description string `json:"description"` } `json:"notCreated"`
}

type jmapErrorPayload struct {
	Type        string `json:"type"`
	Description string `json:"description"`
}

func main() {
	logger := slog.New(slog.NewJSONHandler(os.Stdout, nil))

	listenAddr := envOr("LISTEN_ADDR", defaultListenAddr)
	stalwartURL := strings.TrimRight(envOr("STALWART_URL", defaultStalwartURL), "/")

	b := &bridge{
		stalwartURL: stalwartURL,
		client:      &http.Client{Timeout: requestTimeout},
		logger:      logger,
	}

	srv := &http.Server{
		Addr:              listenAddr,
		Handler:           b.routes(),
		ReadHeaderTimeout: 5 * time.Second,
	}

	go func() {
		logger.Info("starting stalwart-alias-bridge", "addr", listenAddr, "stalwart_url", stalwartURL)
		if err := srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
			logger.Error("server failed", "err", err)
			os.Exit(1)
		}
	}()

	stop := make(chan os.Signal, 1)
	signal.Notify(stop, syscall.SIGINT, syscall.SIGTERM)
	<-stop

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	_ = srv.Shutdown(ctx)
}

func envOr(key, fallback string) string {
	if v := strings.TrimSpace(os.Getenv(key)); v != "" {
		return v
	}
	return fallback
}

func (b *bridge) routes() http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /healthz", b.handleHealth)
	mux.HandleFunc("POST /api/v1/aliases", b.handleCreateAlias)
	return mux
}

func (b *bridge) handleHealth(w http.ResponseWriter, _ *http.Request) {
	writeJSON(w, http.StatusOK, map[string]string{"status": "ok"})
}

func (b *bridge) handleCreateAlias(w http.ResponseWriter, r *http.Request) {
	auth := strings.TrimSpace(r.Header.Get("Authorization"))
	if !strings.HasPrefix(auth, "Bearer ") || len(strings.TrimPrefix(auth, "Bearer ")) == 0 {
		writeJSON(w, http.StatusUnauthorized, map[string]string{"error": "missing bearer token"})
		return
	}

	var reqBody addyCreateRequest
	if err := json.NewDecoder(io.LimitReader(r.Body, 16*1024)).Decode(&reqBody); err != nil && !errors.Is(err, io.EOF) {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": "invalid json body"})
		return
	}

	accountID, status, err := b.getAccountID(r.Context(), auth)
	if err != nil {
		b.logger.Warn("failed to fetch jmap session", "status", status, "err", err)
		if status == http.StatusUnauthorized || status == http.StatusForbidden {
			writeJSON(w, http.StatusUnauthorized, map[string]string{"error": err.Error()})
			return
		}
		writeJSON(w, http.StatusBadGateway, map[string]string{"error": err.Error()})
		return
	}

	desc, forDomain := parseDescription(reqBody.Description)
	email, status, err := b.createMaskedEmail(r.Context(), auth, accountID, desc, forDomain)
	if err != nil {
		b.logger.Warn("failed to create masked email", "status", status, "err", err)
		if status == http.StatusUnauthorized || status == http.StatusForbidden {
			writeJSON(w, http.StatusUnauthorized, map[string]string{"error": err.Error()})
			return
		}
		writeJSON(w, http.StatusBadGateway, map[string]string{"error": err.Error()})
		return
	}

	var resp addyCreateResponse
	resp.Data.Email = email
	writeJSON(w, http.StatusCreated, resp)
}

// parseDescription extracts a clean hostname and origin from Bitwarden's
// Addy.io description ("Website: example.com. Generated by Bitwarden.").
func parseDescription(raw string) (description string, forDomain string) {
	raw = strings.TrimSpace(raw)
	if after, ok := strings.CutPrefix(raw, "Website: "); ok {
		host := after
		if idx := strings.Index(host, ". Generated by Bitwarden"); idx > 0 {
			host = host[:idx]
		}
		host = strings.TrimSuffix(strings.TrimSpace(host), ".")
		if host != "" && !strings.ContainsAny(host, " \t\r\n/") {
			return host, "https://" + host
		}
	}
	if raw == "" {
		return "Bitwarden", ""
	}
	return raw, ""
}

func (b *bridge) getAccountID(ctx context.Context, auth string) (string, int, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, b.stalwartURL+"/jmap/session", nil)
	if err != nil {
		return "", 0, err
	}
	req.Header.Set("Authorization", auth)

	resp, err := b.client.Do(req)
	if err != nil {
		return "", 0, err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return "", resp.StatusCode, fmt.Errorf("stalwart session returned HTTP %d", resp.StatusCode)
	}

	var sess jmapSession
	if err := json.NewDecoder(io.LimitReader(resp.Body, 256*1024)).Decode(&sess); err != nil {
		return "", resp.StatusCode, fmt.Errorf("decode jmap session: %w", err)
	}

	if id := sess.PrimaryAccounts["urn:stalwart:jmap"]; id != "" {
		return id, resp.StatusCode, nil
	}
	if id := sess.PrimaryAccounts["urn:ietf:params:jmap:mail"]; id != "" {
		return id, resp.StatusCode, nil
	}
	return "", resp.StatusCode, errors.New("stalwart session missing primary account")
}

func (b *bridge) createMaskedEmail(ctx context.Context, auth, accountID, desc, forDomain string) (string, int, error) {
	attrs := map[string]any{
		"enable":      true,
		"description": desc,
		"createdBy":   "Bitwarden",
	}
	if forDomain != "" {
		attrs["forDomain"] = forDomain
	}

	payload := jmapRequest{
		Using: []string{"urn:stalwart:jmap", "urn:ietf:params:jmap:core"},
		MethodCalls: [][]any{
			{
				"x:MaskedEmail/set",
				map[string]any{
					"accountId": accountID,
					"create": map[string]any{
						"new-masked-email": attrs,
					},
				},
				"0",
			},
		},
	}

	bodyBytes, err := json.Marshal(payload)
	if err != nil {
		return "", 0, err
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, b.stalwartURL+"/jmap/", bytes.NewReader(bodyBytes))
	if err != nil {
		return "", 0, err
	}
	req.Header.Set("Authorization", auth)
	req.Header.Set("Content-Type", "application/json")

	resp, err := b.client.Do(req)
	if err != nil {
		return "", 0, err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return "", resp.StatusCode, fmt.Errorf("stalwart jmap returned HTTP %d", resp.StatusCode)
	}

	var jr jmapResponse
	if err := json.NewDecoder(io.LimitReader(resp.Body, 256*1024)).Decode(&jr); err != nil {
		return "", resp.StatusCode, fmt.Errorf("decode jmap response: %w", err)
	}

	if len(jr.MethodResponses) == 0 || len(jr.MethodResponses[0]) < 2 {
		return "", resp.StatusCode, errors.New("empty jmap methodResponses")
	}

	var method string
	if err := json.Unmarshal(jr.MethodResponses[0][0], &method); err != nil {
		return "", resp.StatusCode, fmt.Errorf("decode jmap method name: %w", err)
	}

	switch method {
	case "x:MaskedEmail/set":
		var res maskedEmailSetPayload
		if err := json.Unmarshal(jr.MethodResponses[0][1], &res); err != nil {
			return "", resp.StatusCode, fmt.Errorf("decode x:MaskedEmail/set response: %w", err)
		}
		if created, ok := res.Created["new-masked-email"]; ok && created.Email != "" {
			return created.Email, resp.StatusCode, nil
		}
		if notCreated, ok := res.NotCreated["new-masked-email"]; ok {
			if notCreated.Description != "" {
				return "", resp.StatusCode, errors.New(notCreated.Description)
			}
			return "", resp.StatusCode, errors.New("stalwart rejected masked email creation")
		}
		return "", resp.StatusCode, errors.New("missing created email in stalwart response")
	case "error":
		var jerr jmapErrorPayload
		_ = json.Unmarshal(jr.MethodResponses[0][1], &jerr)
		if jerr.Description != "" {
			return "", resp.StatusCode, errors.New(jerr.Description)
		}
		return "", resp.StatusCode, fmt.Errorf("stalwart jmap error: %s", jerr.Type)
	default:
		return "", resp.StatusCode, fmt.Errorf("unexpected jmap method response: %s", method)
	}
}

func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(v)
}
