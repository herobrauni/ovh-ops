func TestCreateAliasSuccess(t *testing.T) {
	var gotAttrs map[string]any
	stalwart := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("Authorization") != "Bearer API_test" {
			w.WriteHeader(http.StatusUnauthorized)
			return
		}
		switch r.URL.Path {
		case "/jmap/session":
			_, _ = w.Write([]byte(`{"primaryAccounts":{"urn:stalwart:jmap":"d"}}`))
		case "/jmap/":
			var body struct {
				MethodCalls [][]json.RawMessage `json:"methodCalls"`
			}
			if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
				t.Fatalf("decode jmap body: %v", err)
			}
			var args struct {
				AccountID string                    `json:"accountId"`
				Create    map[string]map[string]any `json:"create"`
			}
			if err := json.Unmarshal(body.MethodCalls[0][1], &args); err != nil {
				t.Fatalf("decode args: %v", err)
			}
			if args.AccountID != "d" {
				t.Fatalf("expected accountId d, got %q", args.AccountID)
			}
			gotAttrs = args.Create["new-masked-email"]
			_, _ = w.Write([]byte(`{"methodResponses":[["x:MaskedEmail/set",{"created":{"new-masked-email":{"email":"abc@480p.com","id":"1"}}},"0"]]}`))
		default:
			w.WriteHeader(http.StatusNotFound)
		}
	}))
	defer stalwart.Close()

	b := newTestBridge(stalwart.URL)
	req := httptest.NewRequest(
		http.MethodPost,
		"/api/v1/aliases",
		strings.NewReader(`{"domain":"480p.com","description":"Website: example.com. Generated by Bitwarden."}`),
	)
	req.Header.Set("Authorization", "Bearer API_test")
	rec := httptest.NewRecorder()

	b.routes().ServeHTTP(rec, req)

	if rec.Code != http.StatusCreated {
		t.Fatalf("expected 201, got %d: %s", rec.Code, rec.Body.String())
	}

	var resp addyCreateResponse
	if err := json.Unmarshal(rec.Body.Bytes(), &resp); err != nil {
		t.Fatalf("decode response: %v", err)
	}
	if resp.Data.Email != "abc@480p.com" {
		t.Fatalf("expected abc@480p.com, got %q", resp.Data.Email)
	}
	if gotAttrs["description"] != "example.com" {
		t.Fatalf("expected description example.com, got %v", gotAttrs["description"])
	}
	if gotAttrs["forDomain"] != "https://example.com" {
		t.Fatalf("expected forDomain https://example.com, got %v", gotAttrs["forDomain"])
	}
	if gotAttrs["createdBy"] != "Bitwarden" {
		t.Fatalf("expected createdBy Bitwarden, got %v", gotAttrs["createdBy"])
	}
}

func TestCreateAliasStalwartError(t *testing.T) {
	stalwart := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/jmap/session":
			_, _ = w.Write([]byte(`{"primaryAccounts":{"urn:stalwart:jmap":"d"}}`))
		case "/jmap/":
			_, _ = w.Write([]byte(`{"methodResponses":[["x:MaskedEmail/set",{"notCreated":{"new-masked-email":{"description":"quota exceeded"}}},"0"]]}`))
		}
	}))
	defer stalwart.Close()

	b := newTestBridge(stalwart.URL)
	req := httptest.NewRequest(http.MethodPost, "/api/v1/aliases", strings.NewReader(`{"domain":"480p.com","description":"Generated by Bitwarden."}`))
	req.Header.Set("Authorization", "Bearer API_test")
	rec := httptest.NewRecorder()

	b.routes().ServeHTTP(rec, req)

	if rec.Code != http.StatusBadGateway {
		t.Fatalf("expected 502, got %d", rec.Code)
	}
	if !strings.Contains(rec.Body.String(), "quota exceeded") {
		t.Fatalf("expected quota exceeded in body, got %s", rec.Body.String())
	}
}
